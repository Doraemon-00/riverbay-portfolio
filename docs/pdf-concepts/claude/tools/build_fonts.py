"""Build static font instances for PDF embedding.

    python -I tools/build_fonts.py

Why: Chrome's PDF backend embeds *variable* fonts as Type 3 glyph procedures, which
lose hinting, font names and robust text semantics. Static instances embed as normal
TrueType (CID) fonts. Sources are the locally installed Fontsource variable files that
the app already ships (copied into assets/fonts/), OFL-1.1.

Inputs  assets/fonts/nunito/*.woff2, assets/fonts/noto-sans-sc/*.woff2 (+ fontsource-index.css)
Outputs assets/fonts/static/nunito-{700,800}-{latin,latin-ext}.woff2
        assets/fonts/static/noto-sans-sc-{400,700}/noto-sans-sc-<n>.woff2
        assets/fonts/fonts.css  (static faces, unicode-range preserved, local URLs only)
Requires fontTools and brotli. Deterministic for a given fontTools version.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / "assets" / "fonts"
STATIC = FONTS / "static"

NUNITO_RANGES = {
    "latin": "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD",
    "latin-ext": "U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF",
}


STYLE = {400: "Regular", 600: "SemiBold", 700: "Bold", 800: "ExtraBold"}


def instance(src: Path, out: Path, weight: int, family: str) -> None:
    font = TTFont(src)
    static = instancer.instantiateVariableFont(font, {"wght": weight}, updateFontNames=False)
    # Name the instance after its weight so PDF font listings are truthful.
    # Neither licence declares a Reserved Font Name, so the family name is kept.
    style = STYLE[weight]
    names = static["name"]
    for rec in list(names.names):
        if rec.nameID in (1, 2, 3, 4, 6, 16, 17):
            names.removeNames(nameID=rec.nameID)
    names.setName(family, 1, 3, 1, 0x409)
    names.setName("Regular" if weight == 400 else style, 2, 3, 1, 0x409)
    names.setName(f"{family.replace(' ', '')}-{style}; Riverbay static instance", 3, 3, 1, 0x409)
    names.setName(f"{family} {style}", 4, 3, 1, 0x409)
    names.setName(f"{family.replace(' ', '')}-{style}", 6, 3, 1, 0x409)
    static["OS/2"].usWeightClass = weight
    static.flavor = "woff2"
    out.parent.mkdir(parents=True, exist_ok=True)
    static.save(out)


def face(family: str, weight: int, url: str, urange: str) -> str:
    return (
        f"@font-face {{ font-family: '{family}'; font-style: normal; font-weight: {weight}; font-display: block;\n"
        f"  src: url({url}) format('woff2'); unicode-range: {urange}; }}\n"
    )


def main() -> int:
    css = ["/* Generated by tools/build_fonts.py. Static instances, local files only: no remote font requests. */\n"]
    for weight in (700, 800):
        for subset, urange in NUNITO_RANGES.items():
            out = STATIC / f"nunito-{weight}-{subset}.woff2"
            instance(FONTS / "nunito" / f"nunito-{subset}-wght-normal.woff2", out, weight, "Nunito")
            css.append(face("Riverbay Nunito", weight, f"./static/{out.name}", urange))
    for weight, file in ((400, "dm-sans-400.woff2"), (600, "dm-sans-600.woff2")):
        css.append(
            f"@font-face {{ font-family: 'Riverbay DM Sans'; font-style: normal; font-weight: {weight}; font-display: block;\n"
            f"  src: url(./dm-sans/{file}) format('woff2'); }}\n"
        )
    index = (FONTS / "noto-sans-sc" / "fontsource-index.css").read_text(encoding="utf-8")
    # Numbered CJK subsets plus the named latin, latin-ext, cyrillic and vietnamese subsets.
    # The latin subset matters: it holds the SC forms of “ ” ‘ ’ and … used in Chinese text.
    blocks = re.findall(r"url\(\./files/(noto-sans-sc-([a-z0-9-]+?)-wght-normal\.woff2)\).*?unicode-range: ([^;]+);", index, re.S)
    if len(blocks) != 101:
        print(f"unexpected Noto Sans SC subset count: {len(blocks)}", file=sys.stderr)
        return 1
    for weight in (400, 700):
        for file, n, urange in blocks:
            out = STATIC / f"noto-sans-sc-{weight}" / f"noto-sans-sc-{n}.woff2"
            instance(FONTS / "noto-sans-sc" / file, out, weight, "Noto Sans SC")
            css.append(face("Riverbay Noto Sans SC", weight, f"./static/noto-sans-sc-{weight}/{out.name}", urange.strip()))
    (FONTS / "fonts.css").write_text("".join(css), encoding="utf-8", newline="\n")
    print(f"wrote {len(css) - 1} @font-face rules")
    return 0


if __name__ == "__main__":
    sys.exit(main())
